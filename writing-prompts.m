# ✍️ مطالبات كتابة المحتوى وصياغة النصوص

مرحباً بك في قسم مطالبات كتابة المحتوى! تجد هنا أوامر احترافية جاهزة للاستخدام مع تطبيقات الذكاء الاصطناعي (مثل ChatGPT، Claude، وGemini).

---

## 1. كتابة مقال احترافي ومراعي للـ SEO
**الأمر (Prompt):**
> "تصرف كمكاتب محتوى متخصص ومحترف. اكتب مقالاً شاملاً وممتعاً حول [اكتب الموضوع هنا]. اجعل المقال مقسماً إلى مقدمة جذابة، وعناوين فرعية واضحة، وخاتمة مع نصائح عملية. استخدم أسلوباً سهلاً وشيقاً، واحرص على تضمين الكلمات المفتاحية التالية: [أدخل الكلمات المفتاحية]."

---

## 2. إعادة صياغة وتحسين النصوص
**الأمر (Prompt):**
> "قم بإعادة صياغة النص التالي ليكون أكثر احترافية ووضوحاً، مع الحفاظ على المعنى الأصلي وإصلاح أي أخطاء لغوية أو إملائية: [أدخل النص هنا]."

---

## 3. صياغة إعلان تسويقي جذاب للشبكات الاجتماعية
**الأمر (Prompt):**
> "أنت خبير تسويق رقمي. اكتب 3 نماذج لإعلانات قصيرة وجذابة لـ [اسم المنتج/الخدمة]. يجب أن يتضمن كل نموذج: عنواناً يشد الانتباه، شرحاً مختصراً للميزة الأساسية، ودعوة واضحة لاتخاذ إجراء (Call to Action)."

